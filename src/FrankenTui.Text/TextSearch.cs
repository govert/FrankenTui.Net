/// <summary>
/// A search match in native .NET UTF-16 coordinates. The upstream Rust range
/// stores UTF-8 byte offsets; both representations point at the same scalars.
/// </summary>
public readonly record struct SearchResult(int Start, int End)
{
    /// <summary>Returns the match as a native .NET range.</summary>
    public Range Range => Start..End;

    /// <summary>Named constructor corresponding to the upstream <c>new</c>.</summary>
    public static SearchResult New(int start, int end) => new(start, end);

    /// <summary>Extracts the matched text from its source.</summary>
    public string Text(string source) => TextSearch.ExtractRange(source, Start, End);
}

/// <summary>Normalization, case, and terminal-width policy for Unicode search.</summary>
public readonly record struct SearchPolicy(
    NormalizationForm NormForm,
    bool CaseInsensitive,
    WidthMode WidthMode)
{
    /// <summary>NFKC, case-insensitive, standard-width search.</summary>
    public static SearchPolicy Standard { get; } =
        new(NormalizationForm.FormKC, true, global::FrankenTui.Text.WidthMode.Standard);

    /// <summary>NFKC, case-insensitive, CJK ambiguous-wide search.</summary>
    public static SearchPolicy Cjk { get; } =
        new(NormalizationForm.FormKC, true, global::FrankenTui.Text.WidthMode.CjkAmbiguousWide);

    /// <summary>NFC, case-sensitive, standard-width search.</summary>
    public static SearchPolicy ExactNfc { get; } =
        new(NormalizationForm.FormC, false, global::FrankenTui.Text.WidthMode.Standard);
}

/// <summary>A source range enriched with terminal display-column coordinates.</summary>
public readonly record struct PolicySearchResult(
    int Start,
    int End,
    int ColumnStart,
    int ColumnEnd)
{
    /// <summary>Returns the match as a native .NET range.</summary>
    public Range Range => Start..End;

    /// <summary>Extracts the matched text from its source.</summary>
    public string Text(string source) => TextSearch.ExtractRange(source, Start, End);

    /// <summary>Returns the terminal display width of the match.</summary>
    public int DisplayWidth() => ColumnEnd - ColumnStart;
}

/// <summary>Unicode-aware exact, normalized, case-insensitive, and policy search.</summary>
public static class TextSearch
{
    /// <summary>
    /// Computes the display column at a UTF-16 scalar boundary. This is the
    /// native-coordinate counterpart of upstream <c>display_col_at</c>.
    /// </summary>
    public static int DisplayColumnAt(string text, int utf16Offset, WidthMode mode)
    {
        ArgumentNullException.ThrowIfNull(text);
        ValidateUtf16(text, nameof(text));
        WidthModeExtensions.ValidateMode(mode);
        ValidateRange(text, utf16Offset, utf16Offset);

        var width = 0;
        foreach (var rune in text.AsSpan(0, utf16Offset).EnumerateRunes())
        {
            width += mode.CharWidth(rune);
        }

        return width;
    }

    /// <summary>Finds non-overlapping ordinal matches in one string.</summary>
    public static IReadOnlyList<SearchResult> SearchExact(string haystack, string needle)
    {
        ValidateSearchInputs(haystack, needle);
        if (needle.Length == 0)
        {
            return [];
        }

        var results = new List<SearchResult>();
        var start = 0;
        while (start <= haystack.Length)
        {
            var found = haystack.IndexOf(needle, start, StringComparison.Ordinal);
            if (found < 0)
            {
                break;
            }

            results.Add(SearchResult.New(found, found + needle.Length));
            start = found + needle.Length;
        }

        return results;
    }

    /// <summary>Finds ordinal matches, advancing by one Unicode scalar after each start.</summary>
    public static IReadOnlyList<SearchResult> SearchExactOverlapping(string haystack, string needle)
    {
        ValidateSearchInputs(haystack, needle);
        if (needle.Length == 0)
        {
            return [];
        }

        var results = new List<SearchResult>();
        var start = 0;
        while (start <= haystack.Length)
        {
            var found = haystack.IndexOf(needle, start, StringComparison.Ordinal);
            if (found < 0)
            {
                break;
            }

            results.Add(SearchResult.New(found, found + needle.Length));
            start = AdvanceScalar(haystack, found);
        }

        return results;
    }

    /// <summary>Finds non-overlapping matches after lowering ASCII A-Z only.</summary>
    public static IReadOnlyList<SearchResult> SearchAsciiCaseInsensitive(string haystack, string needle)
    {
        ValidateSearchInputs(haystack, needle);
        if (needle.Length == 0)
        {
            return [];
        }

        var loweredHaystack = LowerAscii(haystack);
        var loweredNeedle = LowerAscii(needle);
        var results = new List<SearchResult>();
        var start = 0;
        while (start <= loweredHaystack.Length)
        {
            var found = loweredHaystack.IndexOf(loweredNeedle, start, StringComparison.Ordinal);
            if (found < 0)
            {
                break;
            }

            results.Add(SearchResult.New(found, found + needle.Length));
            start = found + needle.Length;
        }

        return results;
    }

    /// <summary>Finds NFKC plus invariant-lowercase matches in original coordinates.</summary>
    public static IReadOnlyList<SearchResult> SearchCaseInsensitive(string haystack, string needle) =>
        SearchMapped(haystack, needle, TextNormalizer.NormalizeForSearch, StringComparison.Ordinal);

    /// <summary>Finds normalization-equivalent matches in original coordinates.</summary>
    public static IReadOnlyList<SearchResult> SearchNormalized(
        string haystack,
        string needle,
        NormalizationForm form) =>
        SearchMapped(
            haystack,
            needle,
            text => TextNormalizer.Normalize(text, form),
            StringComparison.Ordinal);

    /// <summary>Searches with explicit normalization, case, and width policy.</summary>
    public static IReadOnlyList<PolicySearchResult> SearchWithPolicy(
        string haystack,
        string needle,
        SearchPolicy policy)
    {
        WidthModeExtensions.ValidateMode(policy.WidthMode);

        string Transform(string text)
        {
            var normalized = TextNormalizer.Normalize(text, policy.NormForm);
            return policy.CaseInsensitive ? normalized.ToLowerInvariant() : normalized;
        }

        var matches = SearchMapped(haystack, needle, Transform, StringComparison.Ordinal);
        if (matches.Count == 0)
        {
            return [];
        }

        var results = new List<PolicySearchResult>(matches.Count);
        foreach (var match in matches)
        {
            results.Add(new PolicySearchResult(
                match.Start,
                match.End,
                DisplayColumnAt(haystack, match.Start, policy.WidthMode),
                DisplayColumnAt(haystack, match.End, policy.WidthMode)));
        }

        return results;
    }

    /// <summary>
    /// Compatibility projection over a line-oriented <see cref="TextDocument"/>.
    /// Columns retain their historical native UTF-16 meaning.
    /// </summary>
    public static IReadOnlyList<TextCursor> FindAll(
        TextDocument document,
        string needle,
        StringComparison comparison = StringComparison.OrdinalIgnoreCase)
    {
        ArgumentNullException.ThrowIfNull(document);
        ArgumentNullException.ThrowIfNull(needle);
        if (needle.Length == 0)
        {
            return [];
        }

        var result = new List<TextCursor>();
        for (var lineIndex = 0; lineIndex < document.Lines.Count; lineIndex++)
        {
            var line = document.Lines[lineIndex].PlainText;
            var offset = 0;
            while (offset <= line.Length)
            {
                var found = line.IndexOf(needle, offset, comparison);
                if (found < 0)
                {
                    break;
                }

                result.Add(new TextCursor(lineIndex, found));
                offset = found + needle.Length;
            }
        }

        return result;
    }

    /// <summary>
    /// Compatibility projection that normalizes each line, then maps every
    /// result back to the original line's UTF-16 coordinate space.
    /// </summary>
    public static IReadOnlyList<TextCursor> FindAllNormalized(
        TextDocument document,
        string needle,
        NormalizationForm normalization = NormalizationForm.FormKC,
        StringComparison comparison = StringComparison.OrdinalIgnoreCase)
    {
        ArgumentNullException.ThrowIfNull(document);
        ArgumentNullException.ThrowIfNull(needle);

        var result = new List<TextCursor>();
        for (var lineIndex = 0; lineIndex < document.Lines.Count; lineIndex++)
        {
            var line = document.Lines[lineIndex].PlainText;
            var matches = SearchMapped(
                line,
                needle,
                text => TextNormalizer.Normalize(text, normalization),
                comparison);
            foreach (var match in matches)
            {
                result.Add(new TextCursor(lineIndex, match.Start));
            }
        }

        return result;
    }

    internal static string ExtractRange(string source, int start, int end)
    {
        ArgumentNullException.ThrowIfNull(source);
        ValidateUtf16(source, nameof(source));
        ValidateRange(source, start, end);
        return source[start..end];
    }

    internal static void ValidateUtf16(string text, string parameterName)
    {
        for (var index = 0; index < text.Length; index++)
        {
            var value = text[index];
            if (char.IsHighSurrogate(value))
            {
                if (index + 1 >= text.Length || !char.IsLowSurrogate(text[index + 1]))
                {
                    throw new ArgumentException("Text contains malformed UTF-16.", parameterName);
                }

                index++;
            }
            else if (char.IsLowSurrogate(value))
            {
                throw new ArgumentException("Text contains malformed UTF-16.", parameterName);
            }
        }
    }

    private static IReadOnlyList<SearchResult> SearchMapped(
        string haystack,
        string needle,
        Func<string, string> transform,
        StringComparison comparison)
    {
        ValidateSearchInputs(haystack, needle);
        ArgumentNullException.ThrowIfNull(transform);
        if (needle.Length == 0)
        {
            return [];
        }

        var normalizedNeedle = transform(needle);
        ValidateUtf16(normalizedNeedle, nameof(needle));
        if (normalizedNeedle.Length == 0)
        {
            return [];
        }

        var mapped = BuildMappedText(haystack, transform);
        if (mapped.Text.Length == 0)
        {
            return [];
        }

        var results = new List<SearchResult>();
        var start = 0;
        while (start <= mapped.Text.Length)
        {
            var found = mapped.Text.IndexOf(normalizedNeedle, start, comparison);
            if (found < 0)
            {
                break;
            }

            var normalizedEnd = found + normalizedNeedle.Length;
            var mappedEnd = Math.Min(normalizedEnd, mapped.Text.Length);
            var originalStart = found < mapped.OriginalStarts.Length
                ? mapped.OriginalStarts[found]
                : haystack.Length;
            var originalEnd = mappedEnd > 0
                ? mapped.OriginalEnds[mappedEnd - 1]
                : originalStart;
            var match = SearchResult.New(originalStart, originalEnd);

            if (results.Count == 0 || results[^1] != match)
            {
                results.Add(match);
            }

            start = normalizedEnd;
        }

        return results;
    }

    private static MappedText BuildMappedText(string source, Func<string, string> transform)
    {
        var text = new StringBuilder(source.Length);
        var originalStarts = new List<int>(source.Length);
        var originalEnds = new List<int>(source.Length);
        var elements = StringInfo.GetTextElementEnumerator(source);
        while (elements.MoveNext())
        {
            var originalStart = elements.ElementIndex;
            var element = elements.GetTextElement();
            var originalEnd = originalStart + element.Length;
            var chunk = transform(element);
            ValidateUtf16(chunk, nameof(source));
            if (chunk.Length == 0)
            {
                continue;
            }

            text.Append(chunk);
            for (var index = 0; index < chunk.Length; index++)
            {
                originalStarts.Add(originalStart);
                originalEnds.Add(originalEnd);
            }
        }

        return new MappedText(text.ToString(), [.. originalStarts], [.. originalEnds]);
    }

    private static string LowerAscii(string text) =>
        string.Create(text.Length, text, static (destination, source) =>
        {
            for (var index = 0; index < source.Length; index++)
            {
                var value = source[index];
                destination[index] = value is >= 'A' and <= 'Z'
                    ? (char)(value + ('a' - 'A'))
                    : value;
            }
        });

    private static int AdvanceScalar(string text, int utf16Offset)
    {
        var value = text[utf16Offset];
        return utf16Offset + (char.IsHighSurrogate(value) ? 2 : 1);
    }

    private static void ValidateSearchInputs(string haystack, string needle)
    {
        ArgumentNullException.ThrowIfNull(haystack);
        ArgumentNullException.ThrowIfNull(needle);
        ValidateUtf16(haystack, nameof(haystack));
        ValidateUtf16(needle, nameof(needle));
    }

    private static void ValidateRange(string source, int start, int end)
    {
        if (start < 0 || end < start || end > source.Length)
        {
            throw new ArgumentOutOfRangeException(nameof(start), "Range must be ordered and within the source.");
        }

        if (!IsScalarBoundary(source, start) || !IsScalarBoundary(source, end))
        {
            throw new ArgumentException("Range endpoints must be UTF-16 scalar boundaries.", nameof(start));
        }
    }

    private static bool IsScalarBoundary(string text, int offset) =>
        offset == 0
        || offset == text.Length
        || !(char.IsHighSurrogate(text[offset - 1]) && char.IsLowSurrogate(text[offset]));

    private readonly record struct MappedText(
        string Text,
        int[] OriginalStarts,
        int[] OriginalEnds);
}
