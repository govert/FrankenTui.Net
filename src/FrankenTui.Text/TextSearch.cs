/// <summary>Unicode character-width policy used for search result columns.</summary>
public enum WidthMode
{
    /// <summary>East Asian Ambiguous scalars occupy one terminal cell.</summary>
    Standard,

    /// <summary>East Asian Ambiguous scalars occupy two terminal cells.</summary>
    CjkAmbiguousWide,
}

