    /// <summary>Returns the terminal-cell width of one Unicode scalar.</summary>
    public static int CharWidth(this WidthMode mode, Rune value)
    {
        ValidateMode(mode);

        // unicode-width 0.2.2 scalar exceptions that are not expressible by
        // the BCL general category or the shared terminal-wide ranges.
        if (value.Value == 0x2D7F)
        {
            return 1;
        }

        if (value.Value is 0x115F or 0x17A4 or 0x17D8)
        {
            return 2;
        }

        if (value.Value is >= 0x1F1E6 and <= 0x1F1FF)
        {
            return 1;
        }

        var category = Rune.GetUnicodeCategory(value);
        if (category is UnicodeCategory.Control
            or UnicodeCategory.NonSpacingMark
            or UnicodeCategory.EnclosingMark
            or UnicodeCategory.Format)
        {
            return 0;
        }

        var width = Math.Min(TerminalTextWidth.RuneWidth(value), 2);
        return width == 1
            && mode == WidthMode.CjkAmbiguousWide
            && IsEastAsianAmbiguous(value.Value)
                ? 2
                : width;
    }

    /// <summary>Convenience overload for a BMP scalar.</summary>
    public static int CharWidth(this WidthMode mode, char value)
    {
        if (!Rune.TryCreate(value, out var rune))
        {
            throw new ArgumentException("A UTF-16 surrogate is not a complete Unicode scalar.", nameof(value));
        }

        return mode.CharWidth(rune);
    }

    /// <summary>Returns the summed per-scalar display width of <paramref name="text"/>.</summary>
    public static int StrWidth(this WidthMode mode, string text)
    {
        ArgumentNullException.ThrowIfNull(text);
        ValidateMode(mode);
        TextSearch.ValidateUtf16(text, nameof(text));

        var width = 0;
        foreach (var rune in text.EnumerateRunes())
        {
            width += mode.CharWidth(rune);
        }

        return width;
    }

    internal static void ValidateMode(WidthMode mode)
    {
        if (mode is not WidthMode.Standard and not WidthMode.CjkAmbiguousWide)
        {
            throw new ArgumentOutOfRangeException(nameof(mode), mode, "Unknown search width mode.");
        }
    }

    private static bool IsEastAsianAmbiguous(int scalar)
    {
        var low = 0;
        var high = EastAsianAmbiguousRanges.Length - 1;
        while (low <= high)
        {
            var middle = low + ((high - low) / 2);
            var range = EastAsianAmbiguousRanges[middle];
            if (scalar < range.Start)
            {
                high = middle - 1;
            }
            else if (scalar > range.End)
            {
                low = middle + 1;
            }
            else
            {
                return true;
            }
        }

        return false;
    }
